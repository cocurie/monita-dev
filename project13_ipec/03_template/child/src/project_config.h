// 子機の DeviceID。上位3bit＝Gateway の群番号（0〜7）、下位5bit＝群内の機器番号（1〜31、0は無効）。
//   Gateway の GATEWAY_GROUP_ID と群を揃えること。スプレッドシートの「シート名編集」にも登録する。
//   例: 群0・機器14 → 0x0E
#define CFG_DEVICE_ID          0x2E   // ★2026-09-24 0x0E→0x2E（群0→群1、14番のまま。10進では46）

// 送信間隔（分）の初期値。ダウンリンクで変更すると flash に保存され、以後はそちらが優先される。
//   ★WDT は送信間隔から自動計算するので、ここだけ変えればよい（CLAUDE.md §7）。
#define CFG_SLEEP_MINUTES      2

// HX711 の2段平均の初期値。ダウンリンクで変更可能（変更後は flash の値が優先）。
//   平均回数 = 1回の平均に使う生サンプル数 / メジアン回数 = 平均値を何回取ってメジアンを取るか
#define CFG_SAMPLES_PER_AVG    5
#define CFG_MEASURE_COUNT      5

// 各スロットの割り当て（CH1〜CH4）。0=未使用 / 1=HX711 / 2=I2C加速度 / 3=DS18B20 / 4=VL53L4CD /
//   5=MCP9600（熱電対） / 6,7=ADS1115（電圧）。詳しくは main.cpp の CH_ASSIGN のコメント参照。
#define CFG_CH_ASSIGN          {1, 1, 1, 1}

// LoRa で送るチャネル数（1〜4）。CH1〜CHn を送る。未使用や読み取り失敗のチャネルは「欠測」として送る。
#define CFG_SEND_CH            4

// ひずみ換算係数（送信値[με] = HX711生値 / STRAIN_SCALE）。現場のキャリブレーション値を入れる。
#define CFG_STRAIN_SCALE       1110.0f
